#!/usr/bin/env node
// Sync the per-module database ERD pages from the platform repository.
//
// The pages are generated in apps/backend by `php artisan erd:generate`
// (see Modules/Core app/Support/Erd in the platform repo). This script
// copies docs/erd/*.md into docs/backend/erd/, stripping the generated
// HTML-comment header, and removes pages for modules that no longer exist.
//
// Usage:
//   pnpm sync:erd                       # platform repo at ../baxela
//   pnpm sync:erd ~/src/baxela          # explicit platform repo path
//   BAXELA_REPO=~/src/baxela pnpm sync:erd
//
// Afterwards: pnpm lint:md && pnpm build, then commit the changed pages.

import { readdir, readFile, writeFile, rm } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join, resolve } from 'node:path';

const platformRepo = resolve(
  process.argv[2] ?? process.env.BAXELA_REPO ?? '../baxela',
);
const sourceDir = join(platformRepo, 'apps/backend/docs/erd');
const targetDir = resolve('docs/backend/erd');

if (!existsSync(sourceDir)) {
  console.error(
    `No ERD docs at ${sourceDir}.\n` +
      'Generate them first: docker compose exec app php artisan erd:generate ' +
      `(in ${platformRepo}).`,
  );
  process.exit(1);
}

// Drop the "<!-- Generated by ... -->" header line and the blank line after
// it — HTML comments are not MDX-safe in Docusaurus pages.
function stripGeneratedHeader(markdown) {
  if (!markdown.startsWith('<!--')) {
    return markdown;
  }
  const firstNewline = markdown.indexOf('\n');
  if (firstNewline === -1) {
    return markdown;
  }
  return markdown
    .slice(firstNewline + 1)
    .replace(/^\n/, '');
}

const sourceFiles = (await readdir(sourceDir)).filter((f) => f.endsWith('.md'));

let copied = 0;
for (const file of sourceFiles) {
  const contents = await readFile(join(sourceDir, file), 'utf8');
  await writeFile(join(targetDir, file), stripGeneratedHeader(contents));
  copied += 1;
}

let removed = 0;
for (const file of await readdir(targetDir)) {
  if (file.endsWith('.md') && !sourceFiles.includes(file)) {
    await rm(join(targetDir, file));
    removed += 1;
    console.log(`Removed ${file} (no longer generated)`);
  }
}

console.log(
  `Synced ${copied} ERD page(s) from ${sourceDir} to ${targetDir}` +
    (removed ? `, removed ${removed}` : '') +
    '.\nNext: pnpm lint:md && pnpm build, then commit.',
);
